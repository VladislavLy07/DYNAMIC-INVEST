import { mkdir } from 'node:fs/promises'
import { expect, test } from '@playwright/test'

test('funds use progressive disclosure and retain independent panels through recalculation', async ({ page }) => {
  await page.goto('./#products')
  const products = page.locator('.mini-product').filter({ visible: true })
  await expect(products).toHaveCount(16)
  const first = products.nth(0)
  const second = products.nth(1)
  const third = products.nth(2)
  await expect(first.locator('h3')).toContainText('Финансовая подушка')
  await expect(second.locator('h3')).toContainText('Оборонный')
  await expect(third.locator('h3')).toContainText('Просто. Облигации')
  const firstButton = first.locator('.mini-toggle')
  const secondButton = second.locator('.mini-toggle')
  const panel = first.locator('.mini-slide')
  await expect(firstButton).toHaveAttribute('aria-expanded', 'false')
  await expect(firstButton).toHaveText(/Осторожный.*8\s*%.*Базовый.*12\s*%.*Оптимистичный.*18\s*%/)
  await expect(firstButton).not.toContainText('₽')
  await firstButton.focus()
  await page.keyboard.press('Enter')
  await secondButton.click()
  await expect(firstButton).toHaveAttribute('aria-expanded', 'true')
  await expect(secondButton).toHaveAttribute('aria-expanded', 'true')
  await expect(panel).toBeVisible()
  await expect(panel.locator('h4').first()).toHaveText('До налогообложения → После налогообложения')
  const cautious = panel.getByRole('region', { name: 'Осторожный' })
  await expect(cautious).toContainText(/6,96\s*%/)
  await expect(cautious).toContainText(/69\s600\s*₽/)
  await panel.getByText('Комиссии', { exact: true }).click()
  const fees = panel.locator('details').filter({ has: page.getByText('Комиссии', { exact: true }) })
  await expect(fees).toHaveAttribute('open', '')
  await page.getByLabel('Сумма размещения, ₽').fill('2000000')
  await expect(cautious).toContainText(/139\s200\s*₽/)
  await page.getByLabel('Прочая совместимая база, ₽').fill('2400000')
  await expect(cautious).toContainText(/6,8\s*%/)
  await page.getByLabel('Горизонт расчёта').selectOption('24')
  await expect(firstButton).toContainText(/16,64\s*%/)
  await expect(cautious).toContainText(/14,14\s*%/)
  await page.getByLabel('Налоговый режим').selectOption('flat13')
  await expect(cautious).toContainText(/14,48\s*%/)
  await expect(secondButton).toHaveAttribute('aria-expanded', 'true')
  await expect(fees).toHaveAttribute('open', '')
  await panel.getByText('Официальные источники', { exact: true }).click()
  await expect(panel.getByRole('link', { name: 'Ключевой информационный документ (PDF)' })).toHaveAttribute('href', /^https:\/\/www\.upravlyaem\.ru\//)
  await firstButton.click()
  await expect(panel).toBeHidden()
  await expect(secondButton).toHaveAttribute('aria-expanded', 'true')
})

test('fund scenarios remain horizontal and expanded slides fit desktop, tablet and mobile', async ({ page }) => {
  await page.goto('./')
  const first = page.locator('.mini-product').first()
  await expect(first.locator('.mini-slide')).toBeHidden()
  await page.getByLabel('Сумма размещения, ₽').fill('3500000')
  await page.getByRole('link', { name: 'Весь каталог' }).click()
  await expect(page.getByLabel('Сумма размещения, ₽')).toHaveValue('3500000')
  await first.getByRole('button').click()
  for (const width of [1440, 1024, 768, 360, 320]) {
    await page.setViewportSize({ width, height: 900 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    const positions = await first.locator('.mini-scenarios > span').evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().top))
    expect(new Set(positions).size).toBe(1)
    const screenshotDir = process.env.DI_SCREENSHOTS
    if (screenshotDir && [1440, 360].includes(width)) {
      await mkdir(screenshotDir, { recursive: true })
      await page.screenshot({ path: `${screenshotDir}/investment-slides-${width}.png`, animations: 'disabled' })
    }
  }
})

test('non-fund slides have instrument-specific calculations and contract explanations', async ({ page }) => {
  await page.clock.setFixedTime(new Date('2026-11-27T12:00:00Z'))
  await page.goto('./#products')
  await page.getByRole('button', { name: 'Другие инструменты' }).click()
  const deposit = page.getByRole('article').filter({ has: page.getByRole('button', { name: /^Банковский вклад/ }) })
  await deposit.getByRole('button').click()
  await expect(deposit.locator('.mini-slide')).toContainText(/120\s000\s*₽/)
  const gold = page.getByRole('article').filter({ has: page.getByRole('button', { name: /^Золото / }) })
  await gold.getByRole('button').click()
  await expect(gold.locator('.mini-slide')).toContainText(/1\s048\s600\s*₽/)
  await expect(deposit.locator('.mini-slide')).toBeVisible()
  const pds = page.getByRole('article').filter({ has: page.getByRole('button', { name: /^Программа долгосрочных/ }) })
  await pds.getByRole('button').click()
  await expect(pds.locator('.mini-slide')).toContainText('Для расчёта нужна индивидуальная документация.')
  await expect(pds.locator('.mini-slide')).not.toContainText('₽')
})
