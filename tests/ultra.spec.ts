  await expect(page.locator('.large-result')).toHaveText(/13\s000/)
  await capture(page, 'tax')
  await nav(page, 'Архив')
  await page.getByRole('combobox', { name: 'Год', exact: true }).selectOption('2024')
  await expect(page.getByRole('heading', { name: 'Исторический ряд' })).toBeVisible()
  await expect(page.getByText(/наблюдений в интервале/)).toBeVisible()
  await capture(page, 'archive')
  await page.getByRole('button', { name: 'Будущее', exact: true }).click()
  await nav(page, 'Стратегии')
  await expect(page.getByRole('cell', { name: 'Стрессовый' })).toBeVisible()
  await page.getByRole('combobox', { name: 'Горизонт', exact: true }).selectOption('24')
  await expect(page.getByText('24 мес. · номинальный капитал · прогноз')).toBeVisible()
  await capture(page, 'strategy')
  await nav(page, 'Календарь выплат')
  await page.getByRole('button', { name: 'Год', exact: true }).click()
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: 'ICS', exact: true }).click()
